-- Existing balances: every settlement (replaced / written_off) now names the origin entry it closes.
-- It was oldest-owed-first per supplier and product, so the same order is replayed here. A settlement
-- that spans several origins is split in one row per origin (the first keeps the original row), and the
-- last segment takes the remainder so the total value is exactly the recorded one. Origins already carry
-- their cause (damaged = Por devolver, missing = Por reponer), so no balance is lost or re-valued.
DO $$
DECLARE
  settle RECORD;
  origin RECORD;
  need integer;
  take integer;
  acc_value integer;
  seg_value integer;
  before_value integer;
  after_value integer;
  is_first boolean;
BEGIN
  ALTER TABLE "supplier_pendings" DISABLE TRIGGER "supplier_pendings_no_update_delete";
  CREATE TEMP TABLE "pending_consumed" ("origin_id" uuid PRIMARY KEY, "units" integer NOT NULL);
  FOR settle IN
    SELECT * FROM "supplier_pendings" WHERE "quantity" < 0 AND "settles_id" IS NULL
    ORDER BY "supplier_id", "product_id", "created_at", "id"
  LOOP
    need := -settle."quantity";
    acc_value := 0;
    is_first := true;
    FOR origin IN
      SELECT o."id", o."quantity", o."value_cents", coalesce(c."units", 0) AS "consumed"
      FROM "supplier_pendings" o
      LEFT JOIN "pending_consumed" c ON c."origin_id" = o."id"
      WHERE o."supplier_id" = settle."supplier_id" AND o."product_id" = settle."product_id"
        AND o."type" IN ('damaged', 'missing')
        AND o."quantity" - coalesce(c."units", 0) > 0
      ORDER BY o."created_at", o."id"
    LOOP
      EXIT WHEN need = 0;
      take := least(need, origin."quantity" - origin."consumed");
      before_value := CASE WHEN origin."consumed" = origin."quantity" THEN origin."value_cents"
        ELSE floor((2 * origin."value_cents"::numeric * origin."consumed" + origin."quantity") / (2 * origin."quantity")) END;
      after_value := CASE WHEN origin."consumed" + take = origin."quantity" THEN origin."value_cents"
        ELSE floor((2 * origin."value_cents"::numeric * (origin."consumed" + take) + origin."quantity") / (2 * origin."quantity")) END;
      seg_value := after_value - before_value;
      IF take = need THEN
        seg_value := -settle."value_cents" - acc_value;
      END IF;
      INSERT INTO "pending_consumed" ("origin_id", "units") VALUES (origin."id", take)
        ON CONFLICT ("origin_id") DO UPDATE SET "units" = "pending_consumed"."units" + take;
      IF is_first THEN
        UPDATE "supplier_pendings"
        SET "settles_id" = origin."id", "quantity" = -take, "value_cents" = -seg_value
        WHERE "id" = settle."id";
        is_first := false;
      ELSE
        INSERT INTO "supplier_pendings"
          ("supplier_id", "product_id", "purchase_id", "type", "quantity", "value_cents", "settles_id", "actor_id", "created_at")
        VALUES (settle."supplier_id", settle."product_id", settle."purchase_id", settle."type",
          -take, -seg_value, origin."id", settle."actor_id", settle."created_at");
      END IF;
      acc_value := acc_value + seg_value;
      need := need - take;
    END LOOP;
    IF need > 0 THEN
      RAISE EXCEPTION 'supplier_pendings % settles more than the supplier owed', settle."id";
    END IF;
  END LOOP;
  DROP TABLE "pending_consumed";
  ALTER TABLE "supplier_pendings" ENABLE TRIGGER "supplier_pendings_no_update_delete";
END $$;--> statement-breakpoint
